#!/usr/bin/env node
// Snapshot the awards plugin's recipe manifests into src/registry/recipes.json, so this repository stands alone
// (the shell shows each component's recipe facts; check.mjs reports recipes no component covers yet).
// Usage: node scripts/sync-recipes.mjs [--awards <path to the awards repository>]   (default: ../awards or $AWARDS_DIR)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argIndex = process.argv.indexOf('--awards');
const awards = path.resolve(root, argIndex > -1 ? process.argv[argIndex + 1] : process.env.AWARDS_DIR || '../awards');
const recipesDir = path.join(awards, 'plugins/awards/recipes');
if (!fs.existsSync(recipesDir)) {
  console.error(`no recipes at ${recipesDir}; pass --awards <path to the awards repository>`);
  process.exit(1);
}
const tagsFile = path.join(awards, 'plugins/awards/scripts/data/recipe-tags.json');
const vocab = JSON.parse(fs.readFileSync(tagsFile, 'utf8'));
const pluginJson = JSON.parse(fs.readFileSync(path.join(awards, 'plugins/awards/.claude-plugin/plugin.json'), 'utf8'));

const recipes = {};
for (const dir of fs.readdirSync(recipesDir).sort()) {
  const file = path.join(recipesDir, dir, 'recipe.json');
  if (!fs.existsSync(file)) continue;
  const r = JSON.parse(fs.readFileSync(file, 'utf8'));
  // Lean on purpose: the shell bundles this file, so only what a component page or a script shows.
  recipes[r.id] = {
    title: r.title,
    group: r.group,
    tier: r.tier,
    tags: r.tags,
    deps: r.deps || [],
    seen: (r.seenIn || []).length,
    verified: r.verified?.date || null,
  };
}

const out = {
  about: 'Generated by scripts/sync-recipes.mjs from the awards plugin. Do not edit by hand.',
  plugin: { name: pluginJson.name, version: pluginJson.version, repository: 'https://github.com/BurgiSimon/awards' },
  synced: new Date().toISOString().slice(0, 10),
  groups: Object.fromEntries(Object.entries(vocab.groups).map(([k, v]) => [k, v.title])),
  count: Object.keys(recipes).length,
  recipes,
};
const target = path.join(root, 'src/registry/recipes.json');
fs.writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log(`${out.count} recipes from awards ${out.plugin.version} → ${path.relative(root, target)}`);
